def main() -> None:
    with get_conn() as conn:
        with conn.cursor() as cur:
            cur.execute("SELECT id FROM knowledge_bases WHERE name = %s", (KB_NAME,))
            if not cur.fetchone():
                raise SystemExit(f"知识库不存在: {KB_NAME}")

            inserted = 0
            updated = 0
            for index, (question, answer, category) in enumerate(FAQS, start=1):
                vector_id = f"demo-doc00-faq-{index:03d}"
                cur.execute(
                    "SELECT id FROM faqs WHERE kb_name = %s AND question = %s LIMIT 1",
                    (KB_NAME, question),
                )
                existing = cur.fetchone()
                if existing:
                    cur.execute(
                        """
                        UPDATE faqs
                        SET answer = %s,
                            category = %s,
                            sort_order = %s,
                            enabled = 1,
                            vector_id = COALESCE(vector_id, %s)
                        WHERE id = %s
                        """,
                        (answer, category, index, vector_id, existing["id"]),
                    )
                    updated += 1
                else:
                    cur.execute(
                        """
                        INSERT INTO faqs
                            (kb_name, question, answer, category, sort_order, enabled, vector_id)
                        VALUES (%s, %s, %s, %s, %s, 1, %s)
                        """,
                        (KB_NAME, question, answer, category, index, vector_id),
                    )
                    inserted += 1
        conn.commit()

    print(f"知识库 {KB_NAME} FAQ 已补齐：新增 {inserted} 条，更新 {updated} 条。")


if __name__ == "__main__":
    main()
