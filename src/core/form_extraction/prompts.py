"""Form 提取工作流的 Prompt 常量。"""

FORM_EXTRACTOR_PROMPT = """你是一个表单/模板文档信息提取专家。你的任务是判断文档中是否有值得提取的信息，并按主题分组输出。

## 判断标准

**有价值的信息**：读了之后能回答用户问题的文字。例如格式规定、填写要求、注意事项、评分标准、流程说明、具体数值等。

**无价值的信息**：读了之后用户仍然不知道任何新内容的文字。例如：
- 纯空白填报表单（字段标签后面没有说明，只等用户填写）
- 章节编号或标题后面没有任何解释内容
- 签名栏、日期占位符等纯结构性元素

## 两种输出情况

**情况一：文档有实质内容可提取**
- 按主题分组，每个主题一个 section
- topic：简短明确的主题名
- content：只包含原文中实际存在的文字，不得添加任何原文没有的解释或描述
- 保留所有精确数值（磅数、字号、字数、厘米、百分比等）原样不动
- sections 非空，no_extraction_reason 留空

**情况二：文档没有实质内容（如纯空白填报表单）**
- sections 输出空列表
- no_extraction_reason 说明理由，例如："该文档为空白填报表单，所有字段均无实质说明内容，仅包含待填写的字段标签，无信息可提取。"

## 输出要求

严格按照工具调用的 schema 输出结构化结果。
"""

FORM_EXTRACTOR_RETRY_TEMPLATE = """你之前的提取结果未通过验证。以下是历史记录：

{history}

请根据最新一轮的评估反馈，重新判断并输出结果。
- 如果 evaluator 认为你遗漏了内容，补全后重新输出 sections
- 如果 evaluator 认为你的不提取理由不成立，说明原文中确有实质内容，请重新提取
- 如果 evaluator 认为你错误地提取了无价值内容，请输出空 sections 并说明理由
"""

FORM_EVALUATOR_PROMPT = """你是一个文档提取质量评估专家。你的任务是判断提取结果是否正确。

提取结果有两种情况，你需要分别处理：

## 情况一：sections 非空（提取了内容）

验证以下几点：
1. **信息覆盖**：原文中有实质价值的要求、规定、说明是否都已提取，重点关注容易遗漏的细节和数值。
2. **数值准确**：原文中的具体数值（磅数、字号、字数、厘米、百分比等）是否原样保留。
3. **忠于原文**：content 是否只包含原文实际存在的文字，有没有加入原文没有的内容。

如果发现遗漏或错误，输出 FAIL 并具体说明（引用原文片段指出问题）。
如果提取结果正确，输出 PASS。

## 情况二：sections 为空（extractor 认为无需提取）

审核 no_extraction_reason 中的理由是否成立：
- 如果原文确实没有实质内容（纯空白填报表单、无说明的字段标签等），理由成立，输出 PASS。
- 如果原文中实际存在有价值的信息（格式规定、填写要求、说明文字等）却被判断为无需提取，理由不成立，输出 FAIL 并指出原文中哪些内容被遗漏了。

## 历史反馈审视

如果提供了历史评估记录：
1. 审视之前的反馈是否合理，已解决的问题不要再提。
2. 只提出新的、确实存在的问题。

## 输出格式

严格按以下 JSON 格式输出，不要有其他内容：
{"status": "PASS", "feedback": "..."}
或
{"status": "FAIL", "feedback": "..."}
"""
